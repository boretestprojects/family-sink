export function translate(language, key) {
  return strings[key]?.[languages.findIndex(([code]) => code === language)] ?? strings.unknown_error[1];
}

export function preference(key, value) {
  try {
    if (value === undefined) return localStorage.getItem(`family_sink.${key}`);
    localStorage.setItem(`family_sink.${key}`, value);
  } catch {
    // Browser preferences can be disabled in embedded or private contexts.
  }
}
